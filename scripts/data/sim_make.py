"""Semi-synthetic benchmark: REAL kidney inputs (transcripts, DAPI, cell + nucleus segmentation), SYNTHETIC protein
images generated by known rules, so that specific capabilities can be tested against a known ground truth.

Per-cell gene programmes (log1p CP10k, z-scored per gene, averaged over the programme's genes present in the panel):
  immune  = PTPRC, CD3E, CD8A, MS4A1        prolif = MKI67, TOP2A, PCNA        epith = KRT8, KRT18, EPCAM, CDH1
Channels (rules; level = softplus(2 * programme z)):
  S1 localisation   mem_immune   level(immune) on a 2-px membrane ring of the cell
                    nuc_prolif   level(prolif) inside the nucleus only
                    cyto_epith   level(epith) in the cytoplasm only (cell minus nucleus)
  S2 niche          niche_r15 / niche_r40 / niche_r80: epithelial cells express a membrane protein only when T/immune-cell
                    transcripts (PTPRC, CD3E, CD8A, GZMB) are abundant within r um of the cell centre (excluding itself):
                    level = sigmoid((log1p(inducer within r) - median) / 0.5) * softplus(2 * epith z)
Imaging model: Gaussian PSF (sigma 0.7 px at 0.85 um/px) + additive Gaussian noise (5% of the channel's 99th pct).
Output data/sim/<s>/: Y.npy (6 x H x W float16), cells_truth.parquet (per-cell mean of the noiseless image and the
level), nuc.npy, meta.json; inputs symlinked from the kidney training grid data/xenium_protein_<s>/pilot_L2 (X.npy, tx.npz,
cells.npy, valid.npy, tissue.npy, cell_ids.csv).
usage: sim_make.py rcc|ccrcc
"""
import json, os, sys, time
import numpy as np, pandas as pd, h5py, cv2, scipy.sparse as sp
from scipy.ndimage import gaussian_filter
from scipy.spatial import cKDTree

s = sys.argv[1]
SD = f'data/xenium_protein_{s}/pilot_L2'; OUTS = f'data/xenium_protein_{s}/outs'; OD = f'data/sim/{s}'
os.makedirs(OD, exist_ok=True)
UM = 0.85; rng = np.random.default_rng(0)
PROG = {'immune': ['PTPRC', 'CD3E', 'CD8A', 'MS4A1'], 'prolif': ['MKI67', 'TOP2A', 'PCNA'], 'epith': ['KRT8', 'KRT18', 'EPCAM', 'CDH1']}
INDUCER = ['PTPRC', 'CD3E', 'CD8A', 'GZMB']
CH = ['mem_immune', 'nuc_prolif', 'cyto_epith', 'niche_r15', 'niche_r40', 'niche_r80']


def log(*a): print(time.strftime('%H:%M:%S'), *a, flush=True)


for f in ['X.npy', 'tx.npz', 'cells.npy', 'valid.npy', 'tissue.npy', 'cell_ids.csv']:
    if not os.path.exists(f'{OD}/{f}'): os.symlink(os.path.abspath(f'{SD}/{f}'), f'{OD}/{f}')
lab = np.load(f'{SD}/cells.npy'); H, W = lab.shape
ids = pd.read_csv(f'{SD}/cell_ids.csv')['cell_id'].astype(str).values; n = len(ids) + 1
pos = pd.Series(np.arange(1, n), index=ids)

# ---- per-cell programmes from the 10x count matrix ----
with h5py.File(f'{OUTS}/cell_feature_matrix.h5', 'r') as f:
    m = f['matrix']
    bc = np.array([b.decode() for b in m['barcodes'][:]]); ft = np.array([t.decode() for t in m['features']['feature_type'][:]])
    nm = np.array([t.decode() for t in m['features']['name'][:]])
    X = sp.csc_matrix((m['data'][:], m['indices'][:], m['indptr'][:]), shape=tuple(m['shape'][:])).T.tocsr()
G = X[:, ft == 'Gene Expression'].astype(np.float32); gn = list(nm[ft == 'Gene Expression'])
row = pd.Series(np.arange(len(bc)), index=bc).reindex(ids).values
ok = ~np.isnan(row); row = np.where(ok, row, 0).astype(int)
tot = np.asarray(G.sum(1)).ravel()
L = sp.diags(1e4 / np.maximum(tot, 1)) @ G


def prog_z(genes):
    idx = [gn.index(g) for g in genes if g in gn]
    Z = np.log1p(L[:, idx].toarray()); Z = (Z - Z.mean(0)) / (Z.std(0) + 1e-6)
    z = Z.mean(1)[row]; z[~ok] = np.nan
    return z, [gn[i] for i in idx]


def softplus(x): return np.log1p(np.exp(np.clip(x, -20, 20)))


Z = {}
for k, genes in PROG.items():
    Z[k], used = prog_z(genes); log('programme', k, 'genes used', used)
lev = {'mem_immune': softplus(2 * Z['immune']), 'nuc_prolif': softplus(2 * Z['prolif']), 'cyto_epith': softplus(2 * Z['epith'])}

# niche: inducer transcripts within r of each cell centre
cells = pd.read_parquet(f'{OUTS}/cells.parquet').set_index('cell_id').reindex(ids)
xy = cells[['x_centroid', 'y_centroid']].values.astype(np.float64)
ind_idx = [gn.index(g) for g in INDUCER if g in gn]
ind = np.asarray(G[:, ind_idx].sum(1)).ravel()[row].astype(np.float64); ind[~ok] = 0
tree = cKDTree(xy)
for r in (15, 40, 80):
    A = tree.sparse_distance_matrix(tree, max_distance=r, output_type='coo_matrix').tocsr()
    A.data[:] = 1.0; A.setdiag(0); A.eliminate_zeros()
    d = np.log1p(A @ ind)
    lev[f'niche_r{r}'] = 1 / (1 + np.exp(-(d - np.median(d)) / 0.5)) * softplus(2 * Z['epith'])
    log(f'niche r={r} um: median inducer-neighbour log count {np.median(d):.2f}, mean neighbours {A.getnnz(1).mean():.1f}')
for k in lev: lev[k] = np.nan_to_num(lev[k], nan=0.0)

# ---- compartments on the grid ----
nb = pd.read_parquet(f'{OUTS}/nucleus_boundaries.parquet')
nid = nb['cell_id'].astype(str).values
starts = np.flatnonzero(np.r_[True, nid[1:] != nid[:-1]]); ends = np.r_[starts[1:], len(nid)]
SH = 4
vx = np.round(nb['vertex_x'].values / UM * (1 << SH)).astype(np.int32); vy = np.round(nb['vertex_y'].values / UM * (1 << SH)).astype(np.int32)
nuc = np.zeros((H, W), np.int32)
for a, b in zip(starts, ends):
    k = pos.get(nid[a])
    if k is not None: cv2.fillPoly(nuc, [np.stack([vx[a:b], vy[a:b]], 1)], int(k), lineType=cv2.LINE_8, shift=SH)
nuc = np.where(nuc == lab, nuc, 0)  # nucleus pixels must lie in their own cell
np.save(f'{OD}/nuc.npy', nuc)
edge = np.zeros((H, W), bool)
for dy, dx in ((0, 1), (1, 0)):
    a, b = lab[:H - dy, :W - dx], lab[dy:, dx:]
    e = (a != b); edge[:H - dy, :W - dx] |= e & (a > 0); edge[dy:, dx:] |= e & (b > 0)
ring = cv2.dilate(edge.astype(np.uint8), np.ones((2, 2), np.uint8)).astype(bool) & (lab > 0)
cyto = (lab > 0) & (nuc == 0)
log('compartments: cell px', int((lab > 0).sum()), 'membrane ring px', int(ring.sum()), 'nucleus px', int((nuc > 0).sum()), 'cytoplasm px', int(cyto.sum()))

MASK = {'mem_immune': ring, 'nuc_prolif': nuc > 0, 'cyto_epith': cyto, 'niche_r15': ring, 'niche_r40': ring, 'niche_r80': ring}
Y = np.zeros((len(CH), H, W), np.float16); Yc = np.zeros((len(CH), H, W), np.float16)
truth = pd.DataFrame(dict(label=np.arange(1, n), cell_id=ids))
cnt = np.bincount(lab.ravel(), minlength=n).astype(np.float64)
for j, c in enumerate(CH):
    lv = np.r_[0.0, lev[c]]
    img = np.where(MASK[c], lv[lab], 0.0).astype(np.float32)
    img = gaussian_filter(img, 0.7)
    truth[f'cell_{c}'] = (np.bincount(lab.ravel(), weights=img.ravel().astype(np.float64), minlength=n) / np.maximum(cnt, 1))[1:]
    truth[f'level_{c}'] = lev[c]
    noisy = img + rng.normal(0, 0.05 * np.percentile(img[lab > 0], 99), img.shape).astype(np.float32)
    Y[j] = np.log1p(np.clip(noisy, 0, None)).astype(np.float16); Yc[j] = np.log1p(img).astype(np.float16)
    log(c, 'p99', float(np.percentile(img[lab > 0], 99)))
np.save(f'{OD}/Y.npy', Y); np.save(f'{OD}/Yclean.npy', Yc); truth.to_parquet(f'{OD}/cells_truth.parquet')
# per-cell mean of the noisy (measured-like) image: training target for the cell-level baselines
for j, c in enumerate(CH):
    truth[f'meas_{c}'] = (np.bincount(lab.ravel(), weights=Y[j].ravel().astype(np.float64), minlength=n) / np.maximum(cnt, 1))[1:]
truth.to_parquet(f'{OD}/cells_truth.parquet')
pm = json.load(open(f'{SD}/meta.json'))
json.dump(dict(prots=CH, genes=pm['genes'], own_genes={}, um_per_px=pm['um_per_px'], H=H, W=W, level=pm.get('level', 2),
               rules=dict(programmes=PROG, inducer=INDUCER, psf_sigma_px=0.7, noise='5% of p99')), open(f'{OD}/meta.json', 'w'), indent=1)
log('saved', OD)
