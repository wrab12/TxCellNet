"""Figure 4: semi-synthetic benchmark with known ground truth (real kidney
transcripts, DAPI and segmentation; synthetic proteins generated by known rules).
(a) held-out region as a three-protein composite on black: membrane protein induced in epithelial cells by immune neighbours
    within 40 µm (cyan), immune membrane protein (magenta), nuclear proliferation protein (yellow); ground truth, TxCellNet
    (clean + randomized networks) and the four published methods painted into their cells; second row: zoom (box); under each
    column, one row per channel: cell-level Spearman over the held-out cells of this section (bold: best)
(b) benchmark table: cell-level Spearman per synthetic protein (cell's own program: membrane, nucleus, cytoplasm; induced by
    neighbours within 15/40/80 µm), pixel and within-cell Pearson (mean over two sections), bar = mean cell-level Spearman
    over the six proteins
(c) molecules thinned at test time (mean cell-level Spearman over channels and sections), direct labels at the 25 % end,
    each with a swatch of its series (line ending in the marker) and a leader to its endpoint
Layout (10 pt): a (left) and c (right) share the top band, the table b spans the full width below.
Every printed glyph >= 10 pt (figstyle.print_min10); panel letters 11 pt.
usage: fig4_sim.py DATA_DIR OUT_PREFIX
"""
import glob, sys
import numpy as np, pandas as pd, matplotlib.pyplot as plt
import matplotlib.colors as mcolors
from matplotlib.patches import Rectangle
from matplotlib.lines import Line2D
from skimage.segmentation import find_boundaries
import figstyle
figstyle.print_min10()
from figstyle import W, label, axes_in, save, key, INK, COL, LAB, MK, HERO, HERO_LIGHT, NEUTRAL, LS
from benchtable import order_rows, SHADE
import imaging
from imaging import composite, show, CMY
imaging.MODE.update(mode='rank', gamma=1.8)
FS = 10  # every text in this figure (panel letters: figstyle.PANEL_FS = 11)

DD, OUT = sys.argv[1:3]
S = np.load(f'{DD}/sim_rcc_allm.npz'); CH = [str(c) for c in S['channels']]; lab = S['lab_r']
D = pd.concat([pd.read_csv(f).query("method != 'NicheTrans'") for f in glob.glob(f'{DD}/sim_ens/sim_rows_*.csv')] +
              [pd.read_csv(f) for f in glob.glob(f'{DD}/sim_sota/sim_rows_*.csv')])
KEYS = {'TxCellNet:ens_cr': 'txcellnet', 'TxCellNet:sim_plain': 'txcellnet_clean', 'NicheTrans': 'nichetrans', 'DGAT': 'dgat',
        'SpaMosaic': 'spamosaic', 'totalVI': 'totalvi', 'ridge_niche': 'ridge_niche', 'ridge': 'ridge'}
D = D[D.method.isin(KEYS)].assign(method=lambda d: d.method.map(KEYS))
base = D[D.perturb == 'none']
rho = base[base.section == 'rcc'].groupby(['channel', 'method']).cell_spearman.mean()
NAMES = {'txcellnet_clean': 'Clean only', 'ridge_niche': 'Ridge + nbhd'}  # nbhd = neighbourhood (defined in the caption)
name = lambda m: NAMES.get(m, LAB.get(m, m))

H = 4.48
fig = plt.figure(figsize=(W, H)); REND = fig.canvas.get_renderer()
PAN = {}  # panel id -> axes, for the optional alignment check


def txt(x, y, s, **kw):
    """figure text at (x, y) inches from the top-left corner, 10 pt"""
    kw.setdefault('fontsize', FS); kw.setdefault('color', INK)
    return fig.text(x / W, 1 - y / H, s, **kw)


def width_in(s, weight='normal'):
    t = fig.text(0, 0, s, fontsize=FS, fontweight=weight); w = t.get_window_extent(REND).width / fig.dpi; t.remove()
    return w


# ---------------- geometry (inches) ----------------
T, G, X0, Y0 = 0.66, 0.052, 0.02, 0.62     # image tiles: size, gap, left edge, top edge (6 tiles end at 4.24 in)
XC_AX, AXW = 4.56, 0.58                    # (c): left edge and width of the plot area
XC = XC_AX - 0.26                          # (c): left edge of the block (tick labels)
CHT = 2 * T + G + 0.148                    # (c): plot height (down to the level of the Spearman rows of a)
XLIM = (-0.2, 2.15)
SW_X, SW_L, NAME_DX, LAB_R = 0.02, 0.115, 0.18, 6.48   # (c) labels: swatch start right of the axes, swatch length (line
                                           # ending in the series marker), name start from the swatch start, value right edge

# ---------------- (a) ----------------
SHOW = ['niche_r40', 'mem_immune', 'nuc_prolif']; J = [CH.index(c) for c in SHOW]
label(fig, 0.0, 0.02, 'a'); txt(0.17, 0.02, 'Held-out region', va='top')
key(fig, 1.34, 0.095, [(CMY[0], 'Induced membrane (40 µm)'), (CMY[1], 'Immune membrane'), (CMY[2], 'Nucleus (proliferation)')],
    fs=FS, sq=0.09, pad=0.05, sep=0.2)
cols = [('gt', 'Ground\ntruth', None), ('pred_tx', 'TxCellNet', 'txcellnet'), ('nichetrans', 'NicheTrans', 'nichetrans'),
        ('dgat', 'DGAT', 'dgat'), ('spamosaic', 'SpaMosaic', 'spamosaic'), ('totalvi', 'totalVI', 'totalvi')]
zy, zx, zz = 70, 70, 60  # zoom (60 px = 51 µm)
cellm = lab > 0; edge = find_boundaries(lab, mode='inner').astype(float); zs = (slice(zy, zy + zz), slice(zx, zx + zz))
V = {m: [rho.get((c, m), np.nan) for c in SHOW] for _, _, m in cols if m}
top = [max(V[m][i] for m in V) for i in range(3)]
YS0, YSP = Y0 + 2 * T + G + 0.1, 0.16  # Spearman rows under the tiles: first row centre, row pitch
for c, (k, title, m) in enumerate(cols):
    x = X0 + c * (T + G); painted = k in ('nichetrans', 'dgat', 'spamosaic', 'totalvi')
    chs = [S[k][j].astype(np.float32) for j in J]
    ax = PAN[f'a{c + 1}'] = axes_in(fig, x, Y0, T, T)
    show(ax, composite(chs, cellm, outline=edge, outside=~cellm if painted else None))
    ax.add_patch(Rectangle((zx - 0.5, zy - 0.5), zz, zz, fill=False, ec='white', lw=0.6))
    txt(x + T / 2, Y0 - 0.035, title, ha='center', va='bottom', linespacing=LS)
    if c == 0: imaging.scalebar(ax, 50, text=False)  # lengths in the caption
    ax = PAN[f'a{c + 1}z'] = axes_in(fig, x, Y0 + T + G, T, T)
    show(ax, composite([a[zs] for a in chs], cellm[zs], outline=edge[zs], outside=~cellm[zs] if painted else None), 'bilinear')
    if c == 0: imaging.scalebar(ax, 10, text=False)
    if m is None:
        txt(x + T - 0.02, YS0 + YSP, 'Spearman', ha='right', va='center', color=NEUTRAL)
        continue
    for i in range(3):  # one row per channel: colour square + value (bold: best in the row)
        y = YS0 + i * YSP; best = round(V[m][i], 2) == round(top[i], 2); s = f'{V[m][i]:.2f}'
        w = 0.085 + 0.045 + width_in(s, 'bold'); xl = x + (T - w) / 2
        fig.patches.append(Rectangle((xl / W, 1 - (y + 0.0425 + 0.004) / H), 0.085 / W, 0.085 / H, transform=fig.transFigure,
                                     fc=CMY[i], ec='none', figure=fig))
        txt(xl + 0.13, y, s, ha='left', va='center', fontweight='bold' if best else 'normal')
xa, xb = X0 + 2 * (T + G), X0 + 6 * T + 5 * G; ly = 0.425
fig.add_artist(Line2D([xa / W, xb / W], [1 - ly / H] * 2, color='#9A9A9A', lw=0.6))
txt((xa + xb) / 2, ly - 0.025, 'Per-cell predictions, painted into their cells', ha='center', va='bottom', color=NEUTRAL)

# ---------------- (c) thinning ----------------
label(fig, XC, 0.25, 'c'); txt(XC + 0.17, 0.25, 'Molecules thinned at test time', va='top')
R = D.groupby(['perturb', 'method']).cell_spearman.mean().unstack('method')
xs_ = [('none', '100'), ('thin50', '50'), ('thin25', '25')]
ax = PAN['c'] = axes_in(fig, XC_AX, Y0, AXW, CHT)
txt(XC, Y0 - 0.085, 'Cell-level Spearman', ha='left', va='bottom')   # y-axis title, horizontal above the axis
LINES = ['ridge', 'totalvi', 'spamosaic', 'dgat', 'ridge_niche', 'nichetrans', 'txcellnet_clean', 'txcellnet']
STY = {'txcellnet': dict(color=HERO, lw=2.0, ls='-', marker='D', ms=4.2, zorder=6),
       'txcellnet_clean': dict(color=HERO_LIGHT, lw=1.2, ls=(0, (3, 1.5)), marker='D', ms=3.4, zorder=5)}
sty = lambda m: STY[m] if m in STY else dict(color=COL[m], lw=1.2, ls='-', marker=MK[m], ms=3.8, zorder=4)
for m in LINES:
    ax.plot(range(3), [R.loc[p, m] for p, _ in xs_], mec='white', mew=0.4, **sty(m))
ax.set_xticks(range(3), [l for _, l in xs_]); ax.set_xlim(*XLIM); ax.set_xlabel('Molecules kept (%)', labelpad=2)
YLO = 0.35
ax.set_ylim(YLO, 1.0); ax.set_yticks([0.4, 0.6, 0.8, 1.0])
ax.grid(axis='y', color='#EEEEEE', lw=0.5); ax.set_axisbelow(True)
# direct labels at the 25 % end, ordered as the endpoints. Eight 10-pt labels need more height than the endpoints span, so
# each label carries its own swatch (the series' line ending in its marker, dashed for clean-only) and a leader to its endpoint.
X_IN = lambda x: XC_AX + (x - XLIM[0]) / (XLIM[1] - XLIM[0]) * AXW     # data x -> figure inches
Y_IN = lambda v: Y0 + (1.0 - v) / (1.0 - YLO) * CHT                     # data y -> figure inches (from the top)
items = sorted([(R.loc['thin25', m], m) for m in LINES], reverse=True); yl = [Y_IN(v) for v, _ in items]   # top to bottom
PITCH = 0.155
for _ in range(400):
    for i in range(1, len(yl)):
        if yl[i] - yl[i - 1] < PITCH:
            d = (PITCH - (yl[i] - yl[i - 1])) / 2; yl[i] += d; yl[i - 1] -= d
    lo = yl[-1] - (Y0 + CHT - 0.0775)   # keep the lowest label inside the plot height (clear of the x tick labels)
    if lo > 0: yl = [v - lo for v in yl]
xs0 = X_IN(XLIM[1]) + SW_X; xe = X_IN(2)
for (v, m), y_ in zip(items, yl):
    fw = 'bold' if m == 'txcellnet' else 'normal'; st = sty(m)
    fig.add_artist(Line2D([(xe + 0.035) / W, (xs0 - 0.004) / W], [1 - Y_IN(v) / H, 1 - y_ / H], color='#C4C4C4', lw=0.5))
    ls = (1.0, (3, 1.5)) if m == 'txcellnet_clean' else '-'   # dash phase: dash, gap, dash before the marker
    fig.add_artist(Line2D([xs0 / W, (xs0 + SW_L) / W], [1 - y_ / H] * 2, color=st['color'], lw=st['lw'], ls=ls,
                          solid_capstyle='butt', dash_capstyle='butt'))
    fig.add_artist(Line2D([(xs0 + SW_L) / W], [1 - y_ / H], ls='none', marker=st['marker'], ms=st['ms'], mfc=st['color'],
                          mec='white', mew=0.4))
    txt(xs0 + NAME_DX, y_, name(m), ha='left', va='center', fontweight=fw)
    txt(LAB_R, y_, f'{v:.2f}', ha='right', va='center', fontweight=fw)
print('c: label offsets from their endpoints (in):', {m: round(y_ - Y_IN(v), 3) for (v, m), y_ in zip(items, yl)})
print(f'c: name start {xs0 + NAME_DX:.3f} in, widest name ends {xs0 + NAME_DX + width_in("Ridge + nbhd"):.3f} in, '
      f'values start {LAB_R - width_in("0.65"):.3f} in')

# ---------------- (b) table ----------------
yb = YS0 + 2 * YSP + 0.17
label(fig, 0.0, yb, 'b')
txt(0.17, yb, 'Cell-level Spearman per synthetic protein and image Pearson (two sections)', va='top')
CHC = [('mem_immune', 'Immune\nmembrane'), ('nuc_prolif', 'Nucleus\n(prolif.)'), ('cyto_epith', 'Epithelial\ncytoplasm'),
       ('niche_r15', 'Induced\n15 µm'), ('niche_r40', 'Induced\n40 µm'), ('niche_r80', 'Induced\n80 µm')]
TBL = base.groupby(['method', 'channel']).cell_spearman.mean().unstack('channel')[[c for c, _ in CHC]]
TBL.columns = [h for _, h in CHC]
IM = base.groupby('method')[['pixel_pearson', 'within_cell']].mean(); TBL['Pixel\nPearson'] = IM.pixel_pearson
TBL['Within-cell\nPearson'] = IM.within_cell; TBL['All'] = base.groupby('method').cell_spearman.mean()
TBL = TBL.drop(index='txcellnet_clean')
cols_b = [h for _, h in CHC] + ['Pixel\nPearson', 'Within-cell\nPearson']   # data columns (CSV names as before)
heads = ['Membrane', 'Nucleus', 'Cytoplasm', '15 µm', '40 µm', '80 µm', 'Pixel', 'Within-cell']
groups = [('Cell’s own program', 3), ('Induced by neighbours', 3), ('Image', 2)]
fmt = lambda v: '0' if v == 0 else f'{v:.2f}'


def table10(yb):
    """local 10-pt variant of benchtable.bench_table, laid out in inches: column widths follow the header widths
    (headers shortened under group headers), same row order, shading (rank within column), bold best, bars"""
    blocks = order_rows(TBL, 'All')
    RP, BG = 0.175, 0.055                        # row pitch, gap between the blocks
    NAME_W, GG, BAR_GAP, BAR_L = 1.0, 0.06, 0.20, 0.34   # name column, gap between groups, gap before bars, bar length at 1.0
    # column pitch within a group: neighbouring headers keep >= 0.05 in apart; group header fits its columns
    hw = [width_in(h) for h in heads]; pitch, j0 = [], 0
    for gl, n in groups:
        p = max([0.42] + [(hw[j] + hw[j + 1]) / 2 + 0.05 for j in range(j0, j0 + n - 1)] + [(width_in(gl) + 0.08) / n])
        pitch += [p] * n; j0 += n
    xs, x, bounds = [], NAME_W, np.cumsum([n for _, n in groups])[:-1]
    for j in range(len(cols_b)):
        if j in bounds: x += GG
        xs.append(x); x += pitch[j]
    xbar = x + BAR_GAP
    y_grp, y_hd = yb + 0.27, yb + 0.515         # group headers (centre), column headers (bottom)
    y0 = y_hd + 0.03 + RP / 2                    # first row centre
    ax = axes_in(fig, 0, yb, W - 0.02, H - yb - 0.02); ax.set_xlim(0, W - 0.02); ax.set_ylim(H - yb - 0.02, 0); ax.axis('off')
    Y = lambda y: y - yb
    j0 = 0
    for gl, n in groups:
        xa_, xb_ = xs[j0] + 0.04, xs[j0 + n - 1] + pitch[j0 + n - 1] - 0.04
        ax.plot([xa_, xb_], [Y(y_grp + 0.085)] * 2, color='#9A9A9A', lw=0.6, solid_capstyle='butt')
        ax.text((xa_ + xb_) / 2, Y(y_grp), gl, ha='center', va='center', fontsize=FS, color=INK)
        j0 += n
    rows, y = [], y0
    for block in blocks:
        for m in block: rows.append((m, y)); y += RP
        y += BG
    for j, c in enumerate(cols_b):
        v = TBL[c].astype(float); fin = v.dropna()
        rk = fin.rank(ascending=True, method='min'); rk = (rk - 1) / max(len(fin) - 1, 1)  # 0 = worst, 1 = best
        best = fin.max(); xc = xs[j] + pitch[j] / 2
        ax.text(xc, Y(y_hd), heads[j], ha='center', va='bottom', fontsize=FS, color=INK)
        for m, yy in rows:
            val = v.get(m, np.nan)
            if not np.isfinite(val):
                ax.add_patch(Rectangle((xs[j] + 0.03, Y(yy) - 0.44 * RP), pitch[j] - 0.06, 0.88 * RP, fc='#FAFAFA', ec='none'))
                ax.text(xc, Y(yy), '–', ha='center', va='center', fontsize=FS, color='#9A9A9A'); continue
            colr = SHADE(0.08 + 0.92 * rk[m]); lum = np.dot(mcolors.to_rgb(colr), [0.299, 0.587, 0.114])
            ax.add_patch(Rectangle((xs[j] + 0.03, Y(yy) - 0.44 * RP), pitch[j] - 0.06, 0.88 * RP, fc=colr, ec='none'))
            ax.text(xc, Y(yy), fmt(val), ha='center', va='center', fontsize=FS, color='white' if lum < 0.55 else INK,
                    fontweight='bold' if fmt(val) == fmt(best) else 'normal')
    ax.text(xbar, Y(y_hd), 'Mean of six\nproteins', ha='left', va='bottom', fontsize=FS, color=INK, linespacing=LS)
    best_all = TBL['All'].max()
    for m, yy in rows:
        val = TBL.loc[m, 'All']; L = BAR_L * max(val, 0) / 1.0
        ax.add_patch(Rectangle((xbar, Y(yy) - 0.3 * RP), L, 0.6 * RP, fc=COL[m], ec='none'))
        ax.text(xbar + L + 0.05, Y(yy), f'{val:.3f}', ha='left', va='center', fontsize=FS, color=INK,
                fontweight='bold' if f'{val:.3f}' == f'{best_all:.3f}' else 'normal')
        ax.plot([0.07], [Y(yy)], marker=MK[m], ms=5, mfc=COL[m], mec='white', mew=0.5, clip_on=False)
        ax.text(0.15, Y(yy), name(m), ha='left', va='center', fontsize=FS, color=INK, fontweight='bold' if m == 'txcellnet' else 'normal')
    print(f'table: right edge of the widest bar label {xbar + BAR_L * best_all + 0.05 + width_in(f"{best_all:.3f}", "bold"):.3f} in, '
          f'last row bottom {rows[-1][1] + RP / 2:.3f} in (figure {W} x {H} in)')
    return ax


PAN['b'] = table10(yb)
save(fig, OUT, {'a_spearman_rcc': pd.DataFrame(V, index=SHOW).round(4), 'b_table': TBL.round(4),
                'c_thinning': R.loc[[p for p, _ in xs_], LINES].round(4)},
     panels=PAN, row_groups=[[f'a{i}' for i in range(1, 7)], [f'a{i}z' for i in range(1, 7)]],
     column_groups=[[f'a{i}', f'a{i}z'] for i in range(1, 7)])
print(TBL.round(3).to_string()); print(R.loc[[p for p, _ in xs_], LINES].round(3).to_string())
